import fs from 'node:fs';
import path from 'node:path';
import { policy, keptSourceIsPublic } from '../src/lib/contentPolicy.mjs';

const sourceDir='src/content/posts';
const sources=Object.fromEntries(fs.readdirSync(sourceDir).filter(f=>f.endsWith('.md')).map(file=>[file.slice(0,-3),fs.readFileSync(path.join(sourceDir,file),'utf8')]));
const publicIds=new Set(Object.entries(sources).filter(([slug,s])=>keptSourceIsPublic(slug,s)).map(([slug])=>slug));
const redirects=Object.entries(policy).filter(([,p])=>p.action==='MERGE'&&publicIds.has(p.target)).map(([slug,p])=>({source:`/post/${slug}/`,destination:`/post/${p.target}/`,status:301}));
const active=new Map(redirects.map(r=>[r.source,r.destination]));
const publishedCategories=new Set([...publicIds].map(slug=>sources[slug].match(/^category:\s*["']?([a-z-]+)["']?\s*$/m)?.[1]));
function destination(href) {
  let u;try{u=new URL(href,'https://www.smallspaceorganizationidea.site');}catch{return href;}
  if(u.origin!=='https://www.smallspaceorganizationidea.site')return href;
  const m=u.pathname.match(/^\/post\/([^/]+)\/?$/);
  if(m) {
    if(publicIds.has(m[1]))return `/post/${m[1]}/${u.search}${u.hash}`;
    // Old section anchors are not guaranteed to survive a consolidation.
    return active.get(`/post/${m[1]}/`)??null;
  }
  const c=u.pathname.match(/^\/category\/([^/]+)\/?$/);
  if(c&&!publishedCategories.has(c[1]))return '/';
  return href;
}
let rewritten=0,unlinked=0;
for(const [slug,s] of Object.entries(sources))if(process.argv.includes('--clean-links')&&policy[slug]?.action==='KEEP+IMPROVE') {
  let out=s.replace(/\[([^\]]+)\]\(([^\s)]+)\)/g,(full,label,href)=>{
    if(full.startsWith('!'))return full;
    const dest=destination(href);
    if(dest===null){unlinked++;return label;}
    if(dest!==href){rewritten++;return `[${label}](${dest})`;}
    return full;
  });
  out=out.replace(/<a\s+([^>]*?)href="([^"]+)"([^>]*)>([\s\S]*?)<\/a>/g,(full,before,href,after,label)=>{
    const dest=destination(href);if(dest===null){unlinked++;return label;}if(dest!==href){rewritten++;return `<a ${before}href="${dest}"${after}>${label}</a>`;}return full;
  });
  if(out!==s)fs.writeFileSync(`${sourceDir}/${slug}.md`,out);
}
// Avoid one-post public tag labels as well as one-post tag pages.
const tagsById=new Map([...publicIds].map(slug=>{
  let tags=[];try{tags=JSON.parse(sources[slug].match(/^tags:\s*(\[[^\n]*\])/m)?.[1]??'[]');}catch{}
  return [slug,tags];
}));
const normalize=s=>s.toLowerCase().trim().replace(/&/g,' and ').replace(/[^a-z0-9]+/g,'-').replace(/^-+|-+$/g,'');
const tagCounts=new Map();
for(const tags of tagsById.values())for(const tag of new Set(tags.map(normalize)))tagCounts.set(tag,(tagCounts.get(tag)??0)+1);
for(const [slug,tags]of tagsById) if(process.argv.includes('--clean-links')) {
  const source=fs.readFileSync(`${sourceDir}/${slug}.md`,'utf8');
  const clean=tags.filter(tag=>(tagCounts.get(normalize(tag))??0)>=2&&normalize(tag)!=='onthecorner');
  fs.writeFileSync(`${sourceDir}/${slug}.md`,source.replace(/^tags:\s*\[[^\n]*\]/m,`tags: ${JSON.stringify(clean)}`));
}
// Legacy /tag/ URLs point at the matching category, but only while that
// category still has published posts. After the 2026-10 focus change
// small-spaces is empty, and redirecting to an empty index is a soft 404.
const legacy=['diy-decor','entryway','seasonal','small-spaces']
  .filter(slug=>publishedCategories.has(slug))
  .map(slug=>({source:`/tag/${slug}/`,destination:`/category/${slug}/`,status:301}));
const rules=[...redirects,...legacy];
fs.writeFileSync('public/_redirects','# Generated by scripts/prepare-publishing.mjs; Netlify forced HTTP redirects\n'+rules.flatMap(r=>[`${r.source} ${r.destination} 301!`,`${r.source.replace(/\/$/,'')} ${r.destination} 301!`]).join('\n')+'\n');
fs.writeFileSync('editorial/cloudflare-redirects.txt','# For Cloudflare Pages: replace dist/_redirects with this file before deployment\n'+rules.flatMap(r=>[`${r.source} ${r.destination} 301`,`${r.source.replace(/\/$/,'')} ${r.destination} 301`]).join('\n')+'\n');
fs.writeFileSync('public/.htaccess','# Generated Apache HTTP 301 rules. Requires mod_alias and AllowOverride.\n'+rules.map(r=>`RedirectMatch 301 ^${r.source.replace(/\/$/,'')}/?$ ${r.destination}`).join('\n')+'\n');

/*
  vercel.json — the rules that actually run in production.

  This site is hosted on Vercel, which ignores _redirects (Netlify) and
  .htaccess (Apache). Astro's own `redirects` config cannot help either: in
  `output: 'static'` it can only emit an HTML page carrying a meta refresh, so
  every merged URL answered 200 instead of 301. Vercel evaluates the redirects
  below before it looks at the filesystem, so they take precedence over those
  generated pages.

  Both the slashed and unslashed form of each source is listed because the site
  is built with trailingSlash: 'always'.
*/
const vercelRedirects = rules.flatMap(r => {
  const bare = r.source.replace(/\/$/, '');
  return [
    { source: bare, destination: r.destination, statusCode: 301 },
    { source: `${bare}/`, destination: r.destination, statusCode: 301 },
  ];
});
fs.writeFileSync('vercel.json', JSON.stringify({
  $schema: 'https://openapi.vercel.sh/vercel.json',
  redirects: vercelRedirects,
}, null, 2) + '\n');
const archived=Object.entries(policy).filter(([,p])=>p.action!=='KEEP+IMPROVE'&&!(p.action==='MERGE'&&publicIds.has(p.target))).map(([slug,p])=>({url:`/post/${slug}/`,action:p.action,target:p.target,handling:'noindex,follow retirement notice; original article retained privately'}));
fs.writeFileSync('public/_headers',archived.flatMap(r=>[`${r.url}`,'  X-Robots-Tag: noindex, follow',r.url.replace(/\/$/,''),'  X-Robots-Tag: noindex, follow']).join('\n')+'\n/tag/onthecorner/\n  X-Robots-Tag: noindex, follow\n');
fs.mkdirSync('editorial',{recursive:true});
fs.writeFileSync('editorial/publishing-status.json',JSON.stringify({generatedAt:new Date().toISOString(),kept:48,published:publicIds.size,withheldKeep:48-publicIds.size,activeMergeRedirects:redirects.length,pendingMerges:archived.filter(r=>r.action==='MERGE').length,removed:archived.filter(r=>r.action==='REMOVE').length,redirects,archived,linksRewritten:rewritten,linksUnlinked:unlinked},null,2)+'\n');
console.log(`Publishing: ${publicIds.size} KEEP posts; ${redirects.length} active merge redirects; ${archived.length} noindex retired URLs. Links updated ${rewritten}, unlinked ${unlinked}.`);
